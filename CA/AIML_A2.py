"""# **D. Hill Climbing**

Hill Climbing is a local search algorithm. It starts with an initial state and continuously moves toward a better neighbouring state.
"""

def solve(colors, graph, assignment=None):

    if assignment is None:
        assignment = {}

    # All variables are assigned
    if len(assignment) == len(colors):
        return assignment

    # Select an unassigned variable
    node = next(
        v for v in colors
        if v not in assignment
    )

    # Try different colors
    for color in ['Red', 'Green', 'Blue']:

        # Check constraints
        if all(
            assignment.get(n) != color
            for n in graph[node]
        ):

            assignment[node] = color

            result = solve(
                colors,
                graph,
                assignment
            )

            if result:
                return result

            # Backtrack
            del assignment[node]

    return None


